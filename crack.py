    def generate_scenario_timeseries(self, days: int = 250) -> Tuple[pd.DataFrame, float]:
        np.random.seed(42 if self.mode == "baseline" else 101)
        p_brent, p_ulsd_bbl, p_rbob_bbl, spot_crack = self.compute_margins()

        dt = 1 / 252
        vols = np.array([0.28, 0.38, 0.32]) if self.mode == "baseline" else np.array([0.45, 0.70, 0.50])
        corr = np.array([
            [1.00, 0.85, 0.82],
            [0.85, 1.00, 0.78],
            [0.82, 0.78, 1.00]
        ])
        L = np.linalg.cholesky(corr)

        daily_returns = np.dot(np.random.normal(0, 1, size=(days, 3)), L.T) * (vols * np.sqrt(dt))

        price_paths = np.zeros((days, 3))
        price_paths[-1] = [p_brent, p_ulsd_bbl, p_rbob_bbl]

        for t in range(days - 2, -1, -1):
            price_paths[t] = price_paths[t + 1] / (1 + daily_returns[t + 1])

        dates = pd.date_range(end="2026-10-23", periods=days, freq="B")
        df = pd.DataFrame(price_paths, index=dates, columns=["Brent_bbl", "ULSD_bbl", "RBOB_bbl"])
        df["Crack_321"] = (2 * df["ULSD_bbl"] + 1 * df["RBOB_bbl"] - 3 * df["Brent_bbl"]) / 3.0

        return df, spot_crack

