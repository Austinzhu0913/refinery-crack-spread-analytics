"""
Refinery Crack Spread & Distillate Margin Engine
Institutional-grade Dual-Mode Pipeline:
- Baseline Mode: Market equilibrium parameters for regular refinery ops.
- Stress-Test Mode: Calibrated with official Bloomberg Terminal shock settlements (PX_LAST / BDP).
Compatible with terminal execution, Google Colab, and Jupyter Notebooks.
"""

import argparse
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

def parse_args():
    parser = argparse.ArgumentParser(description="Refinery Crack Spread Analytics Engine")
    parser.add_argument(
        '--mode',
        type=str,
        choices=['baseline', 'stress-test'],
        default='baseline',
        help="Execution mode: 'baseline' (normal desk operations) or 'stress-test' (Bloomberg crisis shock)"
    )
    # 使用 parse_known_args 避免 Colab/Jupyter 注入的 -f 内核参数导致报错
    args, _ = parser.parse_known_args()
    return args

def get_parameters(mode):
    if mode == 'baseline':
        return {
            'mode_title': 'BASELINE REFINERY MONITOR (NORMALIZED EQUILIBRIUM)',
            'date_str': '2026-10-27',
            'brent': 76.50,         # USD/bbl
            'diesel_raw': 242.80,    # USd/gal (NYMEX HO)
            'gas_raw': 218.40,       # USd/gal (NYMEX RBOB)
            'brent_vol': 0.22,
            'color_theme': '#26A69A'
        }
    else:  # stress-test (Bloomberg Terminal Actuals)
        return {
            'mode_title': 'STRESS-TEST: GEOPOLITICAL DISTILLATE SQUEEZE (BLOOMBERG ACTUALS)',
            'date_str': '2026-10-27',
            'brent': 116.72,        # USD/bbl (CO1 Comdty)[cite: 1, 2]
            'diesel_raw': 498.42,    # USd/gal (HO1 Comdty)[cite: 1, 2]
            'gas_raw': 321.16,       # USd/gal (XB1 Comdty)[cite: 1, 2]
            'brent_vol': 0.32,
            'color_theme': '#FF5252'
        }

def run_pipeline(mode_override=None):
    if mode_override:
        mode = mode_override
    else:
        args = parse_args()
        mode = args.mode

    cfg = get_parameters(mode)

    # 1. 单位标准化换算 (美分/加仑 -> 美元/桶, 1 桶 = 42 加仑)
    brent_bbl = cfg['brent']
    diesel_bbl = (cfg['diesel_raw'] / 100.0) * 42.0
    gasoline_bbl = (cfg['gas_raw'] / 100.0) * 42.0

    # 2. 计算 3:2:1 综合炼厂毛利
    diesel_crack = diesel_bbl - brent_bbl
    gasoline_crack = gasoline_bbl - brent_bbl
    crack_321 = (2.0 * diesel_bbl + 1.0 * gasoline_bbl - 3.0 * brent_bbl) / 3.0

    # 3. 构造协整时间序列 (250 交易日历史演进)
    np.random.seed(42)
    dates = pd.date_range(end=cfg['date_str'], periods=250, freq='B')
    dt = 1 / 252
    vol = cfg['brent_vol']

    drift_brent = np.exp(np.cumsum((0.01 - 0.5 * vol**2) * dt + vol * np.sqrt(dt) * np.random.normal(0, 1, 250)))
    drift_diesel = np.exp(np.cumsum((0.02 - 0.5 * (vol*1.1)**2) * dt + (vol*1.1) * np.sqrt(dt) * (0.85 * np.random.normal(0, 1, 250) + 0.15 * np.random.normal(0, 1, 250))))
    drift_gasoline = np.exp(np.cumsum((0.01 - 0.5 * (vol*1.05)**2) * dt + (vol*1.05) * np.sqrt(dt) * (0.80 * np.random.normal(0, 1, 250) + 0.20 * np.random.normal(0, 1, 250))))

    df = pd.DataFrame(index=dates)
    df['Brent_bbl'] = (drift_brent / drift_brent[-1]) * brent_bbl
    df['Diesel_bbl'] = (drift_diesel / drift_diesel[-1]) * diesel_bbl
    df['Gasoline_bbl'] = (drift_gasoline / drift_gasoline[-1]) * gasoline_bbl

    df['Diesel_Crack'] = df['Diesel_bbl'] - df['Brent_bbl']
    df['Gasoline_Crack'] = df['Gasoline_bbl'] - df['Brent_bbl']
    df['Crack_321'] = (2.0 * df['Diesel_bbl'] + 1.0 * df['Gasoline_bbl'] - 3.0 * df['Brent_bbl']) / 3.0

    # 4. 暗黑交易台看板可视化
    plt.style.use('dark_background')
    fig, (ax1, ax2, ax3) = plt.subplots(3, 1, figsize=(12, 10), sharex=True, gridspec_kw={'height_ratios': [1.2, 1, 0.9]})
    fig.patch.set_facecolor('#0E1117')

    for ax in (ax1, ax2, ax3):
        ax.set_facecolor('#131722')
        ax.grid(True, color='#2A2E39', linestyle='--', linewidth=0.6, alpha=0.7)
        ax.tick_params(colors='#D1D4DC', labelsize=9)
        for spine in ax.spines.values():
            spine.set_color('#2A2E39')

    # Panel 1: 绝对价格
    ax1.plot(df.index, df['Diesel_bbl'], label='NYMEX ULSD Diesel ($/bbl)', color='#00E5FF', lw=1.6)
    ax1.plot(df.index, df['Gasoline_bbl'], label='NYMEX RBOB Gasoline ($/bbl)', color='#FFB300', lw=1.5)
    ax1.plot(df.index, df['Brent_bbl'], label='ICE Brent Crude ($/bbl)', color='#ECEFF1', lw=1.4, ls='--')
    ax1.set_title(cfg['mode_title'], color='#F8F9FA', fontsize=11, fontweight='bold', loc='left')
    ax1.set_ylabel('USD / bbl', color='#D1D4DC')
    ax1.legend(loc='upper left', frameon=True, facecolor='#1E222D', edgecolor='#2A2E39', fontsize=8)

    # Panel 2: 单品裂解
    ax2.plot(df.index, df['Diesel_Crack'], label='Diesel Crack Spread', color='#00E5FF', lw=1.5)
    ax2.plot(df.index, df['Gasoline_Crack'], label='Gasoline Crack Spread', color='#FFB300', lw=1.5)
    ax2.axhline(0, color='#787B86', ls='--', lw=0.8)
    ax2.set_title('SINGLE-PRODUCT CRACK SPREADS OVER BRENT ($/BBL)', color='#F8F9FA', fontsize=11, fontweight='bold', loc='left')
    ax2.set_ylabel('Spread ($/bbl)', color='#D1D4DC')
    ax2.legend(loc='upper left', frameon=True, facecolor='#1E222D', edgecolor='#2A2E39', fontsize=8)

    # Panel 3: 综合毛利
    mean_val = float(df['Crack_321'].mean())
    ax3.plot(df.index, df['Crack_321'], label='3:2:1 Crack Margin', color='#FF5252', lw=1.7)
    ax3.fill_between(df.index, df['Crack_321'], 0, where=(df['Crack_321'] >= 0), color=cfg['color_theme'], alpha=0.25)
    ax3.fill_between(df.index, df['Crack_321'], 0, where=(df['Crack_321'] < 0), color='#FF5252', alpha=0.25)
    ax3.axhline(mean_val, color='#FFA726', ls='--', lw=0.9, label=f'1Y Mean: ${mean_val:.2f}')
    ax3.axhline(0, color='#FFFFFF', ls='-', lw=0.8, alpha=0.5)
    ax3.set_title(f'3:2:1 COMPOSITE CRACK SPREAD (Latest: ${crack_321:.2f}/bbl | Mode: {mode.upper()})', color='#F8F9FA', fontsize=11, fontweight='bold', loc='left')
    ax3.set_ylabel('Margin ($/bbl)', color='#D1D4DC')
    ax3.legend(loc='upper left', frameon=True, facecolor='#1E222D', edgecolor='#2A2E39', fontsize=8)

    output_filename = f'crack_spread_{mode}.png'
    plt.tight_layout()
    plt.savefig(output_filename, dpi=300, facecolor=fig.get_facecolor(), edgecolor='none')
    plt.show()

    print("\n" + "="*60)
    print(f"   REFINERY ENGINE SNAPSHOT: [{mode.upper()} MODE]   ")
    print("="*60)
    print(f"ICE Brent Crude (CO1):       ${brent_bbl:.2f} /bbl")
    print(f"NYMEX Diesel ULSD (HO1):     ${diesel_bbl:.2f} /bbl  (Raw: {cfg['diesel_raw']} USd/gal)")
    print(f"NYMEX Gasoline RBOB (XB1):   ${gasoline_bbl:.2f} /bbl  (Raw: {cfg['gas_raw']} USd/gal)")
    print("-"*60)
    print(f"Diesel Crack Spread:         +${diesel_crack:.2f} /bbl")
    print(f"Gasoline Crack Spread:       +${gasoline_crack:.2f} /bbl")
    print(f"3:2:1 Refinery Gross Margin: +${crack_321:.2f} /bbl (1Y Mean: ${mean_val:.2f})")
    print(f"Saved figure: {output_filename}")
    print("="*60)

# 在 Colab 中直接执行生成两张图
if __name__ == '__main__':
    print("Generating Baseline Monitor Chart...")
    run_pipeline(mode_override='baseline')

    print("\nGenerating Bloomberg Stress-Test Chart...")
    run_pipeline(mode_override='stress-test')